function K(t, x, y, facing, order, extra = {}) {
  return { t, x, y, facing, order, ...extra };
}

function coastLine(base, amp, phase) {
  const pts = [];
  for (let y = 0; y <= 640; y += 16) {
    const x = base + Math.sin(y * 0.012 + phase) * amp + Math.sin(y * 0.031 + phase) * amp * 0.35;
    pts.push([x, y]);
  }
  return pts;
}

function coastBand(base, amp, phase) {
  const line = coastLine(base, amp, phase);
  return line.concat([
    [1000, 640],
    [1000, 0],
  ]);
}

function southRiver() {
  const top = [];
  for (let x = 0; x <= 1000; x += 18) {
    top.push([x, 572 + Math.sin(x * 0.013) * 8 + Math.sin(x * 0.041) * 5]);
  }
  return top.concat([
    [1000, 640],
    [0, 640],
  ]);
}

function ellipsePoly(cx, cy, rx, ry, n = 24) {
  const pts = [];
  for (let i = 0; i < n; i++) {
    const a = (i / n) * Math.PI * 2;
    pts.push([cx + Math.cos(a) * rx, cy + Math.sin(a) * ry]);
  }
  return pts;
}

function hillElevation(hills) {
  return function elevation(x, y) {
    let e = 0;
    for (const h of hills) {
      const dx = (x - h.x) / h.rx;
      const dy = (y - h.y) / h.ry;
      const d = dx * dx + dy * dy;
      if (d < 1) {
        const v = h.h * (1 - d) * (1 - d);
        if (v > e) e = v;
      }
    }
    return e;
  };
}

function cannaeRiver() {
  const pts = [];
  for (let y = 0; y <= 640; y += 32) pts.push([78 + Math.sin(y * 0.02) * 14, y]);
  for (let y = 640; y >= 0; y -= 32) pts.push([0, y]);
  return pts;
}

function hastingsElevation(x, y) {
  const ridge = Math.exp(-((y - 198) ** 2) / (2 * 46 * 46));
  const along = 0.62 + 0.38 * Math.exp(-((x - 500) ** 2) / (2 * 320 * 320));
  const woods = y < 100 ? (1 - y / 100) * 0.22 : 0;
  return Math.min(1, ridge * along + woods);
}

function gqokliElevation(x, y) {
  const r = Math.hypot(x - 500, y - 330);
  const rim = Math.exp(-((r - 84) ** 2) / (2 * 32 * 32));
  const foot = Math.exp(-(r * r) / (2 * 150 * 150)) * 0.26;
  return Math.min(1, rim * 0.94 + foot);
}

